#!/usr/bin/env python3
"""Writes ivshape.css: every rounded surface on IV Hub becomes a parallelogram.

Reads the pages' own stylesheets, finds each rule that rounds a corner, and
re-emits that selector with a slanted clip-path and square corners, so a class
added to a page later is covered the next time this is run:

    python3 tools/shape-gen.py

Kept as they were: circles (profile pictures, the seal, dots, switches), tiny
swatches, checkboxes and radios, progress and attendance bars, and the calendar
month grid. Table rows are slanted separately in ivshape.base.css."""
import re, glob, os
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
css=[]
for f in sorted(glob.glob(os.path.join(ROOT,'*.html'))):
    css+=re.findall(r'<style[^>]*>(.*?)</style>',open(f,encoding='utf-8').read(),re.S)
css.append(open(os.path.join(ROOT,'ivtheme.css'),encoding='utf-8').read())

def rules(text):
    text=re.sub(r'/\*.*?\*/','',text,flags=re.S); i=0; n=len(text)
    while i<n:
        j=text.find('{',i)
        if j<0: return
        sel=text[i:j].strip(); d=1; m=j+1
        while m<n and d:
            d+= text[m]=='{'; d-= text[m]=='}'; m+=1
        body=text[j+1:m-1]
        if sel.startswith('@'):
            if re.match(r'@(media|supports)',sel): yield from rules(body)
        else: yield sel,body
        i=m

# Only what has to stay as it is: the seal and logo, people's pictures, the top bar and menus (shaped by hand in ivtheme.css),
# pseudo-elements and decoration that is not a box.
KEEP=re.compile(r'\bavatar|\.uav|logo|seal|\.hm-faces|\.hm-rings|spinner|scroll|\.tn-|\.ivp|\.md-sug|link-sugg|\.wi-|role-menu|\.bell-pop|\.bell-row|iv-banner|ivb-|skel|\.sk\b|\.sk-|\.chk\b|checkbox|radio')
BIG=re.compile(r'panel|pnl|card|tile|\.tw\b|modal|dcard|\.sc\b|lbox|hero|-box|\bbox\b|\.ib\b|hint|banner|cover|drawer|\.um-|rl-ed|dp-|\.sg\b|stat|\.vc\b|mem-card|ev-card|cy-card|mj-list-card|md-sum')
SMALL=re.compile(r'chip|tag|pill|badge|\bbdg|count|\bcap\b|\.ct\b|att-btn|att-key|lead-tag|duty-chip|role-pill|nbadge')
BTN=re.compile(r'btn|button|\.pill|\.add-')
slant={'big':'14px','mid':'8.5px','small':'6px'}
groups={'big':set(),'mid':set(),'small':set()}
for t in css:
    for sel,body in rules(t):
        if re.match(r'^[\d.%,\s]+$|^(from|to)$',sel): continue
        m=re.search(r'border-radius:\s*([^;!}]+)',body)
        if not m: continue
        v=m.group(1).strip()
        if v in ('0','0px','4px 4px 0 0') or re.match(r'^0(px)?$',v): continue
        px=re.findall(r'(\d+)px',v)
        if px and max(map(int,px))<=3: continue          # hairline rounding, nothing to slant
        if v=='50%' or '999' in v and False: pass
        for s_ in [x.strip() for x in sel.split(',')]:
            s_=' '.join(s_.split())
            if ':' in s_.replace(':not(','').replace(':first','').replace(':last','').replace(':nth','') and re.search(r'::|:hover|:focus|:active|:before|:after|:disabled|:checked',s_): continue
            if KEEP.search(s_) or s_.startswith('@') or s_ in ('*','html','body','tr','td','th'): continue
            if not re.match(r'^[.#a-zA-Z\[]',s_): continue
            g='mid' if BTN.search(s_) else 'big' if BIG.search(s_) else 'small' if SMALL.search(s_) else 'mid'
            groups[g].add(s_)
# Things that are a box without being rounded: rows, strips, headers, anything with its own fill or outline.
LAYOUT=re.compile(r'^\.(main|page|app|sidebar|topnav|ph|ha|hd|wrap|wrapper|cellwrap|layout|container|content|shell|sb-nav|sb-bot|sb-logo|nav-item|nav-wrap|cal-grid|grid|pnl-b|iv-pb|body|dlg|mo|overlay|ev-actions|macts|frow|fg|lfg|rp|rp-row|um-grid|pchips|tw-scroll|row|tr|cols?)$')
FILL=re.compile(r'(?:^|;)\s*background(?:-color)?:\s*(?!none|transparent|inherit|initial|unset|var\(--dp\))([^;]+)')
BORD=re.compile(r'(?:^|;)\s*border:\s*(?!0|none)(\d+px|var\(--hairline|var\(--db)')
for t in css:
    for sel,body in rules(t):
        if re.match(r'^[\d.%,\s]+$|^(from|to)$',sel): continue
        if not (FILL.search(body) or BORD.search(body)): continue
        for s_ in [x.strip() for x in sel.split(',')]:
            s_=' '.join(s_.split())
            if not re.match(r'^\.[A-Za-z0-9_-]+(\.[A-Za-z0-9_-]+)*$',s_): continue      # one compound class selector, no states or combinators
            if LAYOUT.match(s_) or KEEP.search(s_): continue
            if any(s_ in groups[g] for g in groups): continue
            g='mid' if BTN.search(s_) else 'big' if BIG.search(s_) else 'small' if SMALL.search(s_) else 'mid'
            groups[g].add(s_)
out=['/* Generated by tools/shape-gen.py. Do not edit by hand. */']
for g in ('big','mid','small'):
    sels=sorted(groups[g])
    # first match in a group wins; later groups override earlier ones only where a selector appears twice
    for s_ in sels:
        out.append('%s{--ivp-sl:%s;clip-path:var(--ivp-poly);border-radius:0!important;border-color:transparent!important;box-shadow:none!important}'%(s_,slant[g]))
open(os.path.join(ROOT,'ivshape.css'),'w',encoding='utf-8').write('\n'.join(out)+'\n')
print({k:len(v) for k,v in groups.items()})
