#!/usr/bin/env python3
"""Writes ivtype.css: one readable type scale for every page of IV Hub.

Reads each rule in the pages' own stylesheets that sets a font size, weight, line
height or letter spacing and re-emits that selector with the site's scale:

    sizes     10 and 11px -> 12, 12 -> 13, 13 -> 14, 14 -> 15 (larger sizes unchanged)
    weights   900 and 800 -> 700, 700 -> 600, 600 -> 500 (body text is 450)
    leading   body-size text gets at least 1.4, large headings stay tight
    tracking  capitals are never spaced wider than 0.06em

Run it again after a page's CSS changes:

    python3 tools/type-gen.py"""
import re, glob, os
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
css=[]
for f in sorted(glob.glob(os.path.join(ROOT,'*.html'))):
    css+=re.findall(r'<style[^>]*>(.*?)</style>',open(f,encoding='utf-8').read(),re.S)
for n in ('ivtheme.css',):
    css.append(open(os.path.join(ROOT,n),encoding='utf-8').read())

def rules(text):
    text=re.sub(r'/\*.*?\*/','',text,flags=re.S); i=0; n=len(text)
    while i<n:
        j=text.find('{',i)
        if j<0: return
        sel=text[i:j].strip(); d=1; m=j+1
        while m<n and d:
            d+= text[m]=='{'; d-= text[m]=='}'; m+=1
        body=text[j+1:m-1]
        if sel.startswith('@'):
            if re.match(r'@(media|supports)',sel): yield from rules(body)
        else: yield sel,body
        i=m

SIZE={10:12,11:12,12:13,13:14,14:15}
WEIGHT={900:700,800:700,700:600,600:500}
SKIP=re.compile(r'^\.(tn-|iv-banner|ivb-|hm-hero)|::|:before|:after|\.ivp|\.mdposter|\.mdp|^html$|^body$|^\*')
sel_rules={}
def put(sel,k,v):
    sel_rules.setdefault(sel,{})[k]=v
for t in css:
    for sel,body in rules(t):
        if re.match(r'^[\d.%,\s]+$|^(from|to)$',sel): continue
        for s_ in [x.strip() for x in sel.split(',')]:
            s_=' '.join(s_.split())
            if not s_ or SKIP.search(s_) or not re.match(r'^[.#a-zA-Z\[]',s_): continue
            m=re.search(r'(?:^|;)\s*font-size:\s*(\d+(?:\.\d+)?)px',body)
            fs=float(m.group(1)) if m else None
            if fs is not None and round(fs) in SIZE and fs==round(fs): put(s_,'font-size','%dpx'%SIZE[round(fs)])
            elif fs is not None and 10<=fs<14: put(s_,'font-size','%dpx'%(round(fs)+1))
            # the font: shorthand carries size, weight and sometimes line height at once
            m=re.search(r'(?:^|;)\s*font:\s*(?:(?:italic|normal|bold)\s+)?(?:(\d{3})\s+)?(\d+(?:\.\d+)?)px(?:/(\d*\.?\d+))?',body)
            if m:
                fsh=float(m.group(2))
                if m.group(1) and int(m.group(1)) in WEIGHT: put(s_,'font-weight',str(WEIGHT[int(m.group(1))]))
                if fsh<14: put(s_,'font-size','%dpx'%SIZE.get(round(fsh),round(fsh)+1))
                lhs=float(m.group(3)) if m.group(3) else None
                if (lhs is None or lhs<1.35) and fsh<=18: put(s_,'line-height','1.4')
            m=re.search(r'(?:^|;)\s*font-weight:\s*(\d{3})',body)
            if m and int(m.group(1)) in WEIGHT: put(s_,'font-weight',str(WEIGHT[int(m.group(1))]))
            m=re.search(r'(?:^|;)\s*font:\s*(\d{3})\b',body)
            if m and int(m.group(1)) in WEIGHT: put(s_,'font-weight',str(WEIGHT[int(m.group(1))]))
            m=re.search(r'(?:^|;)\s*line-height:\s*(\d*\.?\d+)\s*(?:;|$)',body)
            if m and float(m.group(1))<1.35 and (fs is None or fs<=18): put(s_,'line-height','1.4')
            m=re.search(r'(?:^|;)\s*letter-spacing:\s*(\.?\d*\.?\d+)em',body)
            if m and float(m.group(1))>.06: put(s_,'letter-spacing','.06em')
out=['/* Generated by tools/type-gen.py. Do not edit by hand. */',
 'html body{font-size:15px;line-height:1.5;font-weight:450;text-rendering:optimizeLegibility;-webkit-font-smoothing:antialiased;font-variant-numeric:lining-nums;}',
 'p,li,td,.sub,.ph p{line-height:1.5;}',
 'h1,h2,h3,h4{line-height:1.15;letter-spacing:-.01em;font-weight:700;}']
for sel,props in sorted(sel_rules.items()):
    out.append(sel+'{'+';'.join('%s:%s!important'%(k,v) for k,v in props.items())+'}')
# Colours and sizes written into style="" attributes in the markup and in the pages' scripts.
for px in (10,11):
    out.append('[style*="font-size:%dpx"],[style*="font-size: %dpx"]{font-size:12px!important}'%(px,px))
out.append('[style*="font-size:12px"],[style*="font-size: 12px"]{font-size:13px!important}')
for w in (800,900):
    out.append('[style*="font-weight:%d"],[style*="font-weight: %d"]{font-weight:700!important}'%(w,w))
out.append('[style*="letter-spacing:.1"],[style*="letter-spacing:.15"],[style*="letter-spacing:.2"]{letter-spacing:.06em!important}')
# Text that was too faint to read, found by the scan (contrast under 4.5:1).
out+=open(os.path.join(ROOT,'tools','type-fixes.css'),encoding='utf-8').read().splitlines()
open(os.path.join(ROOT,'ivtype.css'),'w',encoding='utf-8').write('\n'.join(out)+'\n')
print(len(sel_rules),'selectors')
