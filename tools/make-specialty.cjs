/* Everything the page script needs, as plain data. */
function config(node, parent){
  const isDiv = !parent;
  const roles = isDiv
    ? [[node.key+'_lead', node.lead],[node.key+'_alead', node.alead]]
    : [[node.key+'_lead', node.role+' Lead'],[node.key+'_alead', node.role+' Assistant Lead'],[node.key+'_team', node.role+' Volunteer'],
       [parent.key+'_lead', parent.lead],[parent.key+'_alead', parent.alead]];
  return {
    kind: isDiv ? 'division' : 'team', name: node.name, icon: node.icon,
    parent: parent ? {name:parent.name, file:parent.file} : null,
    teams: isDiv ? node.teams.map(t=>({key:t.key, name:t.name, icon:t.icon, file:t.file})) : [],
    roles,                       // [permission, label] in order of precedence
    divPerms: parent ? [parent.key+'_lead', parent.key+'_alead'] : [],
    top: IV_TOP, topLabel: TOP_LABEL,
  };
}

