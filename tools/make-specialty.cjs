/* Who may open this page. The database decides what anyone can actually
   change; this only decides what to show. */
async function start(){
  const lib = window.supabase;
  if(!lib || !lib.createClient){
    show('stDeny'); $('denyMsg').textContent = 'Could not reach the server. Check your connection and reload.'; return;
  }
  const sb = lib.createClient(SB_URL, SB_KEY);
  const { data } = await sb.auth.getSession();
  const sess = data && data.session;
  if(!sess || !sess.user){ location.replace('index.html'); return; }
  const { data: prof } = await sb.from('profiles').select('perms').eq('id', sess.user.id).maybeSingle();
  const perms = permList(prof && prof.perms);
  render(perms);
}
function render(perms){
  const mine = PAGE.roles.find(r=>perms.indexOf(r[0]) >= 0);
  const top  = PAGE.top.find(p=>perms.indexOf(p) >= 0);
  if(!mine && !top){ show('stDeny'); return; }
  $('roleChip').textContent = 'Signed in as ' + (mine ? mine[1] : (PAGE.topLabel[top] || 'Leadership'));
  if(PAGE.parent){
    const canDiv = !!top || PAGE.divPerms.some(p=>perms.indexOf(p) >= 0);
    $('crumb').innerHTML = canDiv ? '<a href="' + esc(PAGE.parent.file) + '">' + esc(PAGE.parent.name) + '</a> › IV Hub' : esc(PAGE.parent.name) + ' · IV Hub';
    $('okLede').textContent = "This team's roster page is being built. When it's ready it will appear here — nothing for you to do in the meantime.";
  }
  if(PAGE.kind === 'division' && PAGE.teams.length){
    $('tiles').innerHTML = PAGE.teams.map(t=>'<a class="tile" href="' + esc(t.file) + '"><i>' + t.icon + '</i>' + esc(t.name) + '</a>').join('');
    $('tileWrap').classList.remove('hide');
    $('okLede').textContent = 'Open a team below. The division overview is still being built.';
  }
  show('stOk');
}
