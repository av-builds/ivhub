#!/usr/bin/env python3
"""Demo redesign: writes ivdemo-gen.css from the pages' own stylesheets.

The pages set weights of 700 to 900 and radii of 8 to 999px on hundreds of
classes. Rather than restating each by hand, this reads every rule and emits
the same selector with the demo's weight and radius, so the redesign keeps up
when a page gains a class. Run it after changing any page's CSS:

    python3 tools/demo-gen.py
"""
import re, glob, os
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
css=[]
for f in sorted(glob.glob(os.path.join(ROOT,'*.html'))):
    css+=re.findall(r'<style[^>]*>(.*?)</style>',open(f,encoding='utf-8').read(),re.S)
css.append(open(os.path.join(ROOT,'ivtheme.css'),encoding='utf-8').read())

def rules(text):
    text=re.sub(r'/\*.*?\*/','',text,flags=re.S); i=0; n=len(text)
    while i<n:
        j=text.find('{',i)
        if j<0: return
        sel=text[i:j].strip(); d=1; m=j+1
        while m<n and d:
            d+= text[m]=='{'; d-= text[m]=='}'; m+=1
        body=text[j+1:m-1]
        if sel.startswith('@'):
            if re.match(r'@(media|supports)',sel): yield from rules(body)
        else: yield sel,body
        i=m

bold,round_,circle=set(),set(),set()
for t in css:
    for sel,body in rules(t):
        if '%' in sel and re.match(r'^[\d.%,\s]+$|^(from|to)$',sel): continue      # keyframes
        sel=' '.join(sel.split())
        if re.search(r'font-weight:\s*(700|800|900|bold)',body) or re.search(r'font:\s*(700|800|900)\b',body): bold.add(sel)
        m=re.search(r'border-radius:\s*([^;!}]+)',body)
        if m:
            v=m.group(1).strip()
            (circle if v=='50%' else round_).add(sel)
out=['/* Generated by tools/demo-gen.py. Do not edit by hand. */']
def emit(sels,decl):
    sels=sorted(sels)
    for s in sels: out.append(s+"{"+decl+"}")
emit(bold,'font-weight:600!important')
emit(round_-circle,'border-radius:var(--rad)!important')

# Rules that paint a dark fill of their own (the old navy panels, usually
# translucent). On paper those turn muddy, so they take the surface instead.
dark=set()
for t in css:
    for sel,body in rules(t):
        if re.match(r'^[\d.%,\s]+$|^(from|to)$',sel): continue
        m=re.search(r'background(?:-color)?:\s*(?:rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)|#([0-9a-fA-F]{6})\b)',body)
        if not m: continue
        r,g,b=(int(m.group(1)),int(m.group(2)),int(m.group(3))) if m.group(1) else tuple(int(m.group(4)[i:i+2],16) for i in (0,2,4))
        if (r*299+g*587+b*114)/1000<70: dark.add(' '.join(sel.split()))
for s_ in sorted(dark): out.append(s_+'{background-color:var(--surface2)!important}')
print(len(dark),'dark fills')

# Colours written straight into style="" attributes (in markup and in the
# pages' scripts). Text colours are pointed at the ink tokens by lightness and
# hue; dark fills become the surface. Canvas drawing code is not touched:
# these are CSS attribute selectors and only match elements.
import colorsys
src=''.join(open(f,encoding='utf-8').read() for f in sorted(glob.glob(os.path.join(ROOT,'*.html'))))
def rgb(h):
    h=h.lstrip('#'); h=''.join(c*2 for c in h) if len(h)==3 else h
    return tuple(int(h[i:i+2],16)/255 for i in (0,2,4))
fg,bg={},{}
for m in re.finditer(r'(?<![-\w])color:\s*(#[0-9a-fA-F]{6}|#[0-9a-fA-F]{3})\b',src): fg[m.group(1)]=1
for m in re.finditer(r'background(?:-color)?:\s*(#[0-9a-fA-F]{6}|#[0-9a-fA-F]{3})\b',src): bg[m.group(1)]=1
def tok(hexv):
    r,g,b=rgb(hexv); h,l,s_=colorsys.rgb_to_hls(r,g,b); h*=360
    if s_<.18 or l>.86: return 'var(--ink)' if (l>.8 or l<.25) else 'var(--ink2)'
    if h<20 or h>=335: return 'var(--bad)'
    if 20<=h<65: return 'var(--warn)'
    if 65<=h<170: return 'var(--ok)'
    if l>.8: return 'var(--ink)'
    return 'var(--accent)' if s_>.45 and .3<l<.7 else 'var(--ink2)'
for hexv in sorted(fg):
    for sp in ('',' '): out.append('[style*="color:%s%s" i]{color:%s!important}'%(sp,hexv,tok(hexv)))
for hexv in sorted(bg):
    r,g,b=rgb(hexv); h,l,s_=colorsys.rgb_to_hls(r,g,b)
    t='var(--surface)' if l<.22 else ('var(--surface2)' if l<.4 or l>.9 else None)
    if t:
        for prop in ('background','background-color'):
            for sp in ('',' '): out.append('[style*="%s:%s%s" i]{background-color:%s!important}'%(prop,sp,hexv,t))
print(len(fg),'inline text colours,',len(bg),'inline fills')
open(os.path.join(ROOT,'ivdemo-gen.css'),'w',encoding='utf-8').write('\n'.join(out)+'\n')
print(len(bold),'bold,',len(round_-circle),'rounded selectors')
